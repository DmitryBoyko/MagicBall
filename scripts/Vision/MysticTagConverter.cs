    public static string Convert(string? englishTag)
    {
        if (string.IsNullOrWhiteSpace(englishTag))
            return UnknownArchetype;
        var key = englishTag.Trim();
        if (ByLabel.TryGetValue(key, out var archetype))
            return archetype;
        return $"Архетип Сокрытой Формы ({Capitalize(key)})";
    }

    private static string Capitalize(string text)
    {
        var trimmed = text.Trim();
        if (trimmed.Length == 0)
            return trimmed;
        return char.ToUpperInvariant(trimmed[0]) + trimmed[1..];
    }
